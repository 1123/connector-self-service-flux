#!/usr/bin/env bash
# Developer helper: renders a connector template into connectors/<name>.json and updates
# connectors/kustomization.yaml. Requires jq (and python3 + PyYAML for the local validation).
#
#   scripts/new-connector.sh mq-source   CONNECTOR_NAME=mq-orders-source QUEUE=ORDERS.IN TOPIC=mq.orders
#   scripts/new-connector.sh jdbc-source CONNECTOR_NAME=pg-customers-source TABLE=customers TOPIC=pg.customers \
#                                        MODE=timestamp+incrementing INCREMENTING_COLUMN=id TIMESTAMP_COLUMN=updated_at
#   scripts/new-connector.sh jdbc-sink   CONNECTOR_NAME=pg-customers-sink TOPIC=pg.customers TABLE=customers_copy PK_COLUMNS=id
#
# Delete a connector: rm connectors/<name>.json && scripts/new-connector.sh --sync-kustomization
set -euo pipefail
cd "$(dirname "$0")/.."

sync_kustomization() {
  { echo "# Generated by scripts/new-connector.sh – must list exactly the connector JSON files in this directory."
    echo "apiVersion: kustomize.config.k8s.io/v1beta1"
    echo "kind: Kustomization"
    files=(connectors/*.json)
    if [[ -e "${files[0]}" ]]; then echo "resources:"; for f in "${files[@]}"; do echo "  - $(basename "$f")"; done
    else echo "resources: []"; fi
  } > connectors/kustomization.yaml
}
if [[ "${1:-}" == "--sync-kustomization" ]]; then sync_kustomization; exit 0; fi

type=${1:?usage: $0 <mq-source|jdbc-source|jdbc-sink> KEY=VALUE ...}; shift
tpl="templates/$type.json"
[[ -f "$tpl" ]] || { echo "unknown template '$type' (see templates/)" >&2; exit 1; }

doc=$(cat "$tpl")
declare -A params=()
for kv in "$@"; do
  params[${kv%%=*}]=${kv#*=}
  doc=$(jq --arg k "<<${kv%%=*}>>" --arg v "${kv#*=}" 'walk(if type == "string" then (split($k) | join($v)) else . end)' <<< "$doc")
done
if [[ "$type" == jdbc-source ]]; then
  mode=${params[MODE]:?MODE is required}
  [[ "$mode" == *incrementing* ]] || doc=$(jq 'del(.spec.configs["incrementing.column.name"])' <<< "$doc")
  [[ "$mode" == *timestamp* ]]    || doc=$(jq 'del(.spec.configs["timestamp.column.name"])' <<< "$doc")
fi
left=$(grep -o '<<[A-Z_]*>>' <<< "$doc" | sort -u | tr '\n' ' ' || true)
[[ -z "$left" ]] || { echo "missing parameters: $left" >&2; exit 1; }

name=${params[CONNECTOR_NAME]}
jq . <<< "$doc" > "connectors/$name.json"
sync_kustomization
echo "wrote connectors/$name.json"
if command -v python3 >/dev/null && python3 -c 'import yaml' 2>/dev/null; then python3 ci/validate_connectors.py; fi
